def _build_legal_lens(
    clause_id: str,
    category: str,
    a_clause: Optional[ClassifiedClause],
    risk_profile: Optional[ClauseRiskProfile],
    findings: List[RiskFinding],
    evidence: List[Dict[str, Any]],
) -> LegalLens:
    """Deterministically build the legal-lens analysis from upstream data."""
    evidence_refs: List[str] = [clause_id]
    legal_risk = risk_profile.composite_risk_score if risk_profile else 0.0

    liability = None
    indemnity = None
    jurisdiction = None

    # Aggregate risk flags from all findings for this clause
    all_flags = []
    for f in findings:
        all_flags.extend(f.deterministic_flags)
        evidence_refs.append(f.clause_id)

    # Add any external evidence references
    for ev in evidence:
        ev_id = ev.get("evidence_id", ev.get("id", ""))
        if ev_id:
            evidence_refs.append(ev_id)

    evidence_refs = list(dict.fromkeys(evidence_refs))  # deduplicate, preserve order

    # ── Liability sub-analysis ───────────────────────────────────────
    if category == "liability" or any(
        f.category == "liability" for f in findings
    ):
        liability_findings = [f for f in findings if f.category == "liability"]
        cap_status = "baseline terms"
        if any("uncapped" in fl or "unlimited" in fl or "no cap" in fl for fl in all_flags):
            cap_status = "uncapped — Party B removed liability cap"
        elif any("cap" in fl or "1x" in fl for fl in all_flags):
            cap_status = "capped (baseline preserved)"

        consequential = "not addressed"
        if any("consequential" in fl for fl in all_flags):
            consequential = "consequential damages included — elevated exposure"
        elif any("waive" in fl for fl in all_flags):
            consequential = "consequential damages waived"

        liability = LiabilityAnalysis(
            clause_id=clause_id,
            exposure_summary=(
                f"Liability analysis for {clause_id}: "
                f"{len(liability_findings)} finding(s) detected.  "
                f"Cap status: {cap_status}."
            ),
            cap_status=cap_status,
            consequential_damages=consequential,
            risk_level=_risk_label(legal_risk),
            referenced_clauses=evidence_refs[:10],
        )

    # ── Indemnity sub-analysis ───────────────────────────────────────
    if category == "indemnification" or any(
        f.category == "indemnification" for f in findings
    ):
        indemnity_findings = [f for f in findings if f.category == "indemnification"]
        scope = "standard mutual indemnification"
        if any("sole" in fl or "unlimited" in fl or "broadened" in fl for fl in all_flags):
            scope = "broadened / one-sided indemnification — elevated obligation"

        indemnity = IndemnityAnalysis(
            clause_id=clause_id,
            scope_summary=(
                f"Indemnity analysis for {clause_id}: "
                f"{len(indemnity_findings)} finding(s).  Scope: {scope}."
            ),
            trigger_conditions="Per contract terms (see referenced clauses).",
            cap_or_limit="Subject to overall liability cap unless modified.",
            survival_period="Per contract survival provisions.",
            risk_level=_risk_label(legal_risk),
            referenced_clauses=evidence_refs[:10],
        )

    # ── Jurisdiction sub-analysis ────────────────────────────────────
    if category == "venue_jurisdiction" or category == "governing_law" or any(
        f.category == "venue_jurisdiction" for f in findings
    ):
        jury_waiver = any("jury" in fl or "waive jury" in fl for fl in all_flags)
        arb = "none specified"
        if any("arbitration" in fl for fl in all_flags):
            arb = "mandatory arbitration clause detected"

        jurisdiction = JurisdictionAnalysis(
            clause_id=clause_id,
            governing_law="Per contract — see referenced clause.",
            venue="Per contract — Party B may have proposed venue change.",
            arbitration_clause=arb,
            jury_waiver=jury_waiver,
            risk_level=_risk_label(legal_risk * 0.8),
            referenced_clauses=evidence_refs[:10],
        )

    # ── Summary ──────────────────────────────────────────────────────
    summary_parts = []
    if liability:
        summary_parts.append(f"Liability: {liability.cap_status}")
    if indemnity:
        summary_parts.append(f"Indemnity: {indemnity.scope_summary[:80]}")
    if jurisdiction:
        summary_parts.append(f"Jurisdiction: arbitration={jurisdiction.arbitration_clause[:40]}")
    if not summary_parts:
        summary_parts.append(
            f"No specialised legal findings for {clause_id} "
            f"(category: {category}, risk: {legal_risk:.1f}/10)."
        )

    return LegalLens(
        clause_id=clause_id,
        liability=liability,
        indemnity=indemnity,
        jurisdiction=jurisdiction,
        evidence_references=evidence_refs,
        legal_risk_score=round(min(legal_risk, 10.0), 2),
        legal_summary="; ".join(summary_parts),
    )


def _build_commercial_lens(
    clause_id: str,
    category: str,
    risk_profile: Optional[ClauseRiskProfile],
    findings: List[RiskFinding],
    financial_context: Dict[str, Any],
) -> CommercialLens:
    """Deterministically build the commercial-lens analysis."""
    risk_score = risk_profile.composite_risk_score if risk_profile else 0.0
    arr_value = financial_context.get("arr_value", "")
    variance_ceiling = financial_context.get("variance_ceiling")

    evidence_refs: List[str] = [clause_id]

    # ── ARR Impact ───────────────────────────────────────────────────
    arr_exposure_pct = 0.0
    arr_narrative = "No material ARR impact identified."
    if category in ("liability", "indemnification") and risk_score >= 4.0:
        arr_exposure_pct = min(risk_score * 8.0, 80.0)
        arr_narrative = (
            f"Clause {clause_id} risk score {risk_score:.1f}/10 creates potential "
            f"exposure of ~{arr_exposure_pct:.0f}% of contract value "
            f"({'ARR: ' + arr_value if arr_value else 'ARR not specified'})."
        )
    elif category == "payment" and risk_score >= 3.0:
        arr_exposure_pct = min(risk_score * 5.0, 50.0)
        arr_narrative = (
            f"Payment term changes in {clause_id} may affect cash-flow by "
            f"~{arr_exposure_pct:.0f}% of deal value."
        )
    elif category == "termination" and risk_score >= 5.0:
        arr_exposure_pct = min(risk_score * 10.0, 100.0)
        arr_narrative = (
            f"Termination provisions in {clause_id} could put up to "
            f"~{arr_exposure_pct:.0f}% of ARR at risk if triggered."
        )

    arr_impact = ArrImpact(
        clause_id=clause_id,
        deal_value_at_risk=arr_value or "Not specified",
        arr_exposure_pct=round(arr_exposure_pct, 1),
        narrative=arr_narrative,
        referenced_clauses=evidence_refs,
    )

    # ── Payment / Float Impact ───────────────────────────────────────
    payment_float = None
    if category == "payment":
        payment_findings = [f for f in findings if f.category == "payment"]
        baseline = "Per Party A standard terms"
        proposed = "Per Party B redline"
        float_delta = 0
        for f in payment_findings:
            for flag in f.deterministic_flags:
                flag_l = flag.lower()
                if "net 10" in flag_l:
                    float_delta = -50  # 50 days earlier than Net 60
                elif "net 15" in flag_l:
                    float_delta = -45
                elif "net 7" in flag_l:
                    float_delta = -53
                elif "immediate" in flag_l or "upon receipt" in flag_l:
                    float_delta = -60

        payment_float = PaymentFloatImpact(
            clause_id=clause_id,
            baseline_terms=baseline,
            proposed_terms=proposed,
            float_delta_days=float_delta,
            cash_flow_narrative=(
                f"Party B's payment terms shift float by {float_delta} days "
                f"relative to baseline.  Negative values indicate accelerated "
                f"payment obligation for Party A."
            ) if float_delta != 0 else "No material float impact detected.",
            referenced_clauses=evidence_refs,
        )

    # ── Relationship Impact ──────────────────────────────────────────
    rel_risk = "neutral"
    rel_narrative = f"Clause {clause_id} changes are within normal negotiation range."
    is_aggressive = risk_profile.is_aggressive_deviation if risk_profile else False

    if is_aggressive:
        rel_risk = "adversarial"
        rel_narrative = (
            f"Aggressive deviation in {clause_id} may signal adversarial posture.  "
            f"Consider whether relationship preservation warrants concession."
        )
    elif risk_score >= 6.0:
        rel_risk = "negative"
        rel_narrative = (
            f"High-risk modifications in {clause_id} (score {risk_score:.1f}/10) "
            f"could strain the commercial relationship if not addressed collaboratively."
        )
    elif risk_score >= 3.0:
        rel_risk = "neutral"
        rel_narrative = (
            f"Moderate changes in {clause_id} — typical of active negotiation."
        )
    else:
        rel_risk = "positive"
        rel_narrative = (
            f"Minimal changes in {clause_id} — alignment is strong."
        )

    relationship = RelationshipImpact(
        clause_id=clause_id,
        relationship_risk=rel_risk,
        narrative=rel_narrative,
        referenced_clauses=evidence_refs,
    )

    # ── Commercial risk score ────────────────────────────────────────
    # Weight: ARR exposure most, payment next, relationship least
    commercial_risk = round(min(
        arr_exposure_pct * 0.08  # Normalise 0–80 → 0–6.4
        + (abs(payment_float.float_delta_days) * 0.03 if payment_float else 0.0)
        + {"positive": 0, "neutral": 1, "negative": 3, "adversarial": 5}.get(rel_risk, 1),
        10.0,
    ), 2)

    return CommercialLens(
        clause_id=clause_id,
        arr_impact=arr_impact,
        payment_float=payment_float,
        relationship=relationship,
        commercial_risk_score=commercial_risk,
        commercial_summary=(
            f"ARR exposure: {arr_exposure_pct:.0f}%.  "
            f"Relationship: {rel_risk}.  "
            f"Commercial risk: {commercial_risk}/10."
        ),
    )


def _build_candidate_comparison(
    neg_result: ClauseNegotiationResult,
    recommended_strategy: str,
) -> List[CandidateComparison]:
    """Build the comparison matrix from negotiation engine candidates."""
    comparisons: List[CandidateComparison] = []
    for c in neg_result.candidates:
        comparisons.append(CandidateComparison(
            strategy=c.strategy.value,
            label=c.label,
            party_a_utility=c.party_a_utility.weighted_total,
            party_b_utility=c.party_b_utility.weighted_total,
            compromise_score=c.compromise_score,
            is_recommended=(c.strategy.value == recommended_strategy),
            is_pareto_efficient=c.is_pareto_efficient,
            disqualification_reason=(
                "Exceeds variance ceiling" if c.exceeds_variance_ceiling else ""
            ),
        ))
    return comparisons


def _select_recommendation(
    neg_result: ClauseNegotiationResult,
    legal_risk: float,
    commercial_risk: float,
) -> Optional[CompromiseCandidate]:
    """
    Select the best candidate, preferring Pareto-efficient ones.

    Tie-breaking: if legal risk is high (≥7), prefer strategies that limit
    Party A exposure.  If commercial risk is high (≥7), prefer strategies
    that preserve the deal.
    """
    candidates = list(neg_result.pareto_frontier) if neg_result.pareto_frontier else list(neg_result.candidates)
    if not candidates:
        return neg_result.recommended

    # Filter out variance-ceiling violations unless everything violates
    within_ceiling = [c for c in candidates if not c.exceeds_variance_ceiling]
    pool = within_ceiling if within_ceiling else candidates

    # Sort by compromise_score, break ties by strategy preference
    strategy_order = {
        CompromiseStrategy.CONCEDE_WITH_GUARD: 0,
        CompromiseStrategy.SPLIT_MIDPOINT: 1,
        CompromiseStrategy.NARROW_SCOPE: 2,
        CompromiseStrategy.TRADE_OFF: 3,
        CompromiseStrategy.ACCEPT_PARTY_A: 4,
        CompromiseStrategy.ACCEPT_PARTY_B: 5,
        CompromiseStrategy.ESCALATE: 6,
    }

    # If legal risk is very high, penalise accept_party_b
    if legal_risk >= 7.0:
        strategy_order[CompromiseStrategy.ACCEPT_PARTY_B] = 10
        strategy_order[CompromiseStrategy.ACCEPT_PARTY_A] = 1

    # If commercial/relationship risk is high, penalise accept_party_a
    if commercial_risk >= 7.0:
        strategy_order[CompromiseStrategy.ACCEPT_PARTY_A] = 10
        strategy_order[CompromiseStrategy.CONCEDE_WITH_GUARD] = 0

    pool.sort(
        key=lambda c: (-c.compromise_score, strategy_order.get(c.strategy, 5)),
    )

    return pool[0]


def _compute_confidence(
    legal_risk: float,
    commercial_risk: float,
    candidate: Optional[CompromiseCandidate],
    is_non_negotiable: bool,
    has_aggressive_deviation: bool,
) -> float:
    """
    Arbiter confidence in the recommendation (0–100%).

    Formula:
        base = candidate.compromise_score (0–100)
        penalties:
            −15 if aggressive deviation
            −10 if combined risk ≥ 7
            −5  if combined risk ≥ 4
        bonuses:
            +10 if non-negotiable (clear path)
            +5  if Pareto-efficient

    Clamped to [10, 95] — never 0% (always some basis) and never 100%
    (human review always required).
    """
    if candidate is None:
        return 10.0

    base = candidate.compromise_score
    combined = legal_risk * 0.55 + commercial_risk * 0.45

    penalty = 0.0
    if has_aggressive_deviation:
        penalty += 15.0
    if combined >= 7.0:
        penalty += 10.0
    elif combined >= 4.0:
        penalty += 5.0

    bonus = 0.0
    if is_non_negotiable:
        bonus += 10.0
    if candidate.is_pareto_efficient:
        bonus += 5.0

    return round(max(10.0, min(95.0, base - penalty + bonus)), 1)


def _risk_label(score: float) -> str:
    if score >= 8.0:
        return "critical"
    elif score >= 6.0:
        return "high"
    elif score >= 3.5:
        return "moderate"
    return "low"


