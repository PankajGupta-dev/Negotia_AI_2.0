"""
Agent 3: Arbiter-3 — AI Judge & Deal Mediator.

Consumes upstream outputs from Agent 1 (Party A baseline), Agent 2 (Party B
risk analysis), matter financial context, and scored negotiation candidates
to produce a dual-lens verdict for every contested clause.

Two independent analysis lenses:
    LEGAL   — liability, indemnity, jurisdiction, evidence context, legal risk
    COMMERCIAL — ARR impact, payment/float impact, relationship, commercial risk

Then synthesises:
    • Recommended compromise candidate
    • Rationale with clause_id and evidence references
    • Candidate comparison matrix
    • Confidence level
    • Proposed clause language

Design constraints:
    • Every claim MUST reference a clause_id or evidence source
    • No invented laws, precedents, or citations are presented as facts
    • Human review remains mandatory — output explicitly flags this
    • LLM prompts are short and structured
    • Deterministic fallback when no LLM key is configured
"""

