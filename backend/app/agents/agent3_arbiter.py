    # ═════════════════════════════════════════════════════════════════════════
    # Deterministic Verdict Pipeline
    # ═════════════════════════════════════════════════════════════════════════

    def _deterministic_verdicts(
        self,
        negotiation_output: NegotiationEngineOutput,
        a1_map: Dict[str, ClassifiedClause],
        a2_map: Dict[str, ClauseRiskProfile],
        a2_findings_map: Dict[str, List[RiskFinding]],
        neg_map: Dict[str, ClauseNegotiationResult],
        financial_context: Dict[str, Any],
        external_evidence: List[Dict[str, Any]],
        matter_id: Optional[str],
    ) -> ArbiterOutput:
        verdicts: List[ClauseVerdict] = []
        escalated: List[str] = []
        legal_risks: List[float] = []
        commercial_risks: List[float] = []
        confidences: List[float] = []

        for neg_result in negotiation_output.clause_results:
            c_id = neg_result.clause_id
            category = neg_result.category
            title = neg_result.title
            section = neg_result.section_number

            a1_clause = a1_map.get(c_id)
            risk_profile = a2_map.get(c_id)
            findings = a2_findings_map.get(c_id, [])
            is_aggressive = risk_profile.is_aggressive_deviation if risk_profile else False

            # ── Build legal lens ─────────────────────────────────────
            legal_lens = _build_legal_lens(
                c_id, category, a1_clause, risk_profile, findings, external_evidence,
            )

            # ── Build commercial lens ────────────────────────────────
            commercial_lens = _build_commercial_lens(
                c_id, category, risk_profile, findings, financial_context,
            )

            # ── Select recommendation ────────────────────────────────
            recommended = _select_recommendation(
                neg_result,
                legal_lens.legal_risk_score,
                commercial_lens.commercial_risk_score,
            )

            # ── Build candidate comparison ───────────────────────────
            rec_strategy = recommended.strategy.value if recommended else ""
            comparison = _build_candidate_comparison(neg_result, rec_strategy)

            # ── Proposed clause text ─────────────────────────────────
            proposed_text = recommended.proposed_text if recommended else ""

            # ── Rationale (deterministic) ────────────────────────────
            rationale = self._build_deterministic_rationale(
                c_id, title, category, legal_lens, commercial_lens,
                recommended, neg_result.is_non_negotiable, is_aggressive,
            )

            # ── Confidence ───────────────────────────────────────────
            confidence = _compute_confidence(
                legal_lens.legal_risk_score,
                commercial_lens.commercial_risk_score,
                recommended,
                neg_result.is_non_negotiable,
                is_aggressive,
            )

            # ── Combined risk ────────────────────────────────────────
            combined_risk = round(
                legal_lens.legal_risk_score * 0.55
                + commercial_lens.commercial_risk_score * 0.45,
                2,
            )

            # ── Evidence trail ───────────────────────────────────────
            evidence_cited = list(legal_lens.evidence_references)
            for f in findings:
                evidence_cited.extend(f.deterministic_flags[:3])
            evidence_cited = list(dict.fromkeys(evidence_cited))

            # ── Escalation check ─────────────────────────────────────
            if recommended and recommended.strategy == CompromiseStrategy.ESCALATE:
                escalated.append(c_id)

            verdict = ClauseVerdict(
                clause_id=c_id,
                section_number=section,
                title=title,
                category=category,
                legal_lens=legal_lens,
                commercial_lens=commercial_lens,
                recommended_strategy=rec_strategy,
                recommended_label=recommended.label if recommended else "",
                proposed_clause_text=proposed_text,
                rationale=rationale,
                confidence=confidence,
                requires_human_review=True,
                candidate_comparison=comparison,
                combined_risk_score=combined_risk,
                evidence_cited=evidence_cited,
            )
            verdicts.append(verdict)
            legal_risks.append(legal_lens.legal_risk_score)
            commercial_risks.append(commercial_lens.commercial_risk_score)
            confidences.append(confidence)

        # ── Aggregates ───────────────────────────────────────────────
        n = len(verdicts) or 1
        agg_legal = round(sum(legal_risks) / n, 2)
        agg_commercial = round(sum(commercial_risks) / n, 2)
        agg_combined = round(agg_legal * 0.55 + agg_commercial * 0.45, 2)
        agg_confidence = round(sum(confidences) / n, 1)

        exec_summary = (
            f"Arbiter-3 reviewed {len(verdicts)} clause(s).  "
            f"Aggregate legal risk: {agg_legal}/10.  "
            f"Aggregate commercial risk: {agg_commercial}/10.  "
            f"Combined risk: {agg_combined}/10.  "
            f"Mean confidence: {agg_confidence}%.  "
            f"{len(escalated)} clause(s) escalated to human counsel.  "
            f"Human review is mandatory for all recommendations."
        )

        self.emit_event(thought=exec_summary, matter_id=matter_id)

        return ArbiterOutput(
            matter_id=matter_id,
            verdicts=verdicts,
            aggregate_legal_risk=agg_legal,
            aggregate_commercial_risk=agg_commercial,
            aggregate_combined_risk=agg_combined,
            aggregate_confidence=agg_confidence,
            escalated_clause_ids=escalated,
            executive_summary=exec_summary,
            human_review_required=True,
        )

    def _build_deterministic_rationale(
        self,
        clause_id: str,
        title: str,
        category: str,
        legal_lens: LegalLens,
        commercial_lens: CommercialLens,
        recommended: Optional[CompromiseCandidate],
        is_non_negotiable: bool,
        is_aggressive: bool,
    ) -> str:
        """Build an explainable rationale string referencing evidence."""
        if recommended is None:
            return f"No candidates available for {clause_id}.  Manual drafting required."

        parts: List[str] = []

        # Opening
        strategy_label = recommended.strategy.value.replace("_", " ").title()
        parts.append(
            f"For clause {clause_id} ({title}), the Arbiter recommends "
            f"'{strategy_label}' (compromise score: {recommended.compromise_score}/100)."
        )

        # Non-negotiable override
        if is_non_negotiable:
            parts.append(
                f"This clause is flagged as non-negotiable by Party A — "
                f"the baseline position is enforced (ref: {clause_id})."
            )
            return "  ".join(parts)

        # Legal basis
        parts.append(
            f"Legal risk: {legal_lens.legal_risk_score}/10.  "
            f"{legal_lens.legal_summary}"
        )

        # Commercial basis
        parts.append(
            f"Commercial risk: {commercial_lens.commercial_risk_score}/10.  "
            f"{commercial_lens.commercial_summary}"
        )

        # Aggressive deviation warning
        if is_aggressive:
            parts.append(
                f"⚠ Aggressive deviation detected in {clause_id}.  "
                f"Party B's markup represents a material departure from baseline."
            )

        # Utility comparison
        parts.append(
            f"Party A utility: {recommended.party_a_utility.weighted_total}, "
            f"Party B utility: {recommended.party_b_utility.weighted_total}, "
            f"joint surplus: {recommended.joint_surplus}, "
            f"balance: {recommended.balance}."
        )

        # Evidence trail
        refs = legal_lens.evidence_references[:5]
        if refs:
            parts.append(f"Evidence cited: {', '.join(refs)}.")

        # Human review reminder
        parts.append(
            "This recommendation requires mandatory human counsel review "
            "before adoption."
        )

        return "  ".join(parts)

