# ── Legal Lens ───────────────────────────────────────────────────────────────

class LiabilityAnalysis(BaseModel):
    """Legal assessment of liability exposure for a clause."""
    clause_id: str
    exposure_summary: str = ""
    cap_status: str = ""          # e.g. "capped at 1x ARR", "uncapped", "mutual"
    consequential_damages: str = ""
    risk_level: str = "moderate"  # low | moderate | high | critical
    referenced_clauses: List[str] = Field(default_factory=list)


class IndemnityAnalysis(BaseModel):
    """Legal assessment of indemnification obligations."""
    clause_id: str
    scope_summary: str = ""
    trigger_conditions: str = ""
    cap_or_limit: str = ""
    survival_period: str = ""
    risk_level: str = "moderate"
    referenced_clauses: List[str] = Field(default_factory=list)


class JurisdictionAnalysis(BaseModel):
    """Legal assessment of venue / governing law provisions."""
    clause_id: str
    governing_law: str = ""
    venue: str = ""
    arbitration_clause: str = ""
    jury_waiver: bool = False
    risk_level: str = "moderate"
    referenced_clauses: List[str] = Field(default_factory=list)


class LegalLens(BaseModel):
    """Complete legal-lens analysis for a single clause."""
    clause_id: str
    liability: Optional[LiabilityAnalysis] = None
    indemnity: Optional[IndemnityAnalysis] = None
    jurisdiction: Optional[JurisdictionAnalysis] = None
    evidence_references: List[str] = Field(
        default_factory=list,
        description="Clause IDs, risk flags, or external evidence keys cited.",
    )
    legal_risk_score: float = Field(default=0.0, ge=0.0, le=10.0)
    legal_summary: str = ""
    disclaimer: str = (
        "This analysis is generated by an AI system and does not constitute "
        "legal advice.  Human counsel review is mandatory before any action."
    )


